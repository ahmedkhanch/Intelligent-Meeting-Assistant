"""PV (Procès-Verbal) — central data contract for every call."""

from datetime import datetime
from typing import Literal
from uuid import uuid4

from pydantic import BaseModel, Field

from app.models.task import TaskItem


class Participant(BaseModel):
    """One person on the call.

    ``phone_number`` and ``role`` are optional because the LLM frequently
    cannot infer them — especially in multi-party meetings or from undiarized
    audio (the realtime STT does not separate speakers).
    """

    name: str
    phone_number: str = ""
    role: str = ""
    side: Literal["left", "right"]


class PV(BaseModel):
    """A full Procès-Verbal — generated by the AI from a call transcript.

    This is the central document. Every call produces exactly one PV.
    """

    pv_id: str = Field(default_factory=lambda: str(uuid4()))
    call_date: datetime
    call_type: Literal["#appel-commercial", "#appel-tech"]
    left: Participant
    right: Participant
    additional_participants: list[Participant] = Field(
        default_factory=list,
        description=(
            "Any speakers beyond the primary left/right pair, e.g. multi-party "
            "meetings. Empty for a two-person call. Each entry carries a "
            "`side` field so Ora-side vs external is preserved."
        ),
    )
    subject: str
    compte_rendu: str = Field(
        description="AI-generated narrative summary of the entire call"
    )
    actions: list[TaskItem] = Field(
        default_factory=list,
        description=(
            "For commercial calls: action items with owner + deadline. "
            "For tech calls: todo list with owner + deadline + difficulty."
        ),
    )
    meeting_created: bool = False
    meeting_datetime: datetime | None = None
